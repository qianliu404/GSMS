const { chromium } = require('E:/GSMS/frontend/node_modules/playwright-core')
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const p = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage()
  await p.goto('http://127.0.0.1:8080/login', { waitUntil: 'networkidle' })
  await p.fill('input[placeholder="请输入工号或用户名"]', 'admin')
  await p.fill('input[placeholder="请输入登录密码"]', process.env.GSMS_PASSWORD || '')
  await p.click('button:has-text("登 录")')
  await p.waitForTimeout(2000)
  await p.goto('http://127.0.0.1:8080/system/workflow', { waitUntil: 'networkidle' })
  await p.waitForTimeout(1800)

  // 打开新增节点弹窗
  await p.locator('button:has-text("新增节点")').first().click()
  await p.waitForTimeout(600)
  const labels = await p.$$eval('.el-dialog .el-form-item__label', (els) => els.map((e) => e.textContent.trim()))
  console.log('弹窗字段:', JSON.stringify(labels))
  const codeBox = await p.locator('.code-box').first().innerText().catch(() => 'NONE')
  console.log('状态码区域:', JSON.stringify(codeBox))
  await p.fill('.el-dialog input[placeholder="如：伤情复核"]', '伤情复核')
  await p.waitForTimeout(400)
  await p.screenshot({ path: 'E:/GSMS/deploy/shots/deadline-fix/08-node-create.png', clip: { x: 380, y: 100, width: 700, height: 620 } })
  await b.close()
})().catch((e) => { console.error('ERR', e.message); process.exit(1) })
