const { chromium } = require('playwright-core')
const BASE = 'http://127.0.0.1:8080'
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await (await browser.newContext({ viewport: { width: 1500, height: 1000 } })).newPage()
  await page.goto(BASE + '/login', { waitUntil: 'networkidle' })
  await page.fill('input[placeholder="请输入工号或用户名"]', 'admin')
  await page.fill('input[placeholder="请输入登录密码"]', process.env.GSMS_PASSWORD || '')
  await page.click('button:has-text("登 录")')
  await page.waitForTimeout(2200)
  await page.goto(BASE + '/cases/124', { waitUntil: 'networkidle' })
  await page.waitForTimeout(1800)
  const handle = await page.evaluateHandle(() => [...document.querySelectorAll('.card')]
    .find((c) => c.querySelector('.card-head h2')?.innerText.trim() === '争议关联案件'))
  const el = handle.asElement()
  await el.scrollIntoViewIfNeeded()
  await page.waitForTimeout(300)
  await el.screenshot({ path: 'E:/GSMS/deploy/shots/relations/rel-card-no-add.png' })
  await browser.close()
})()
