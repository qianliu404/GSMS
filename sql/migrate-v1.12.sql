-- =============================================================
-- v1.12 节点截止日期：起算日改为「发生日期」+ 允许人工调整
--
-- 背景：
--   1) 截止日期统一以案件「发生日期」为起算日（原按进入节点当天起算），
--      存量案件因此也能算出完整的时间轴。
--   2) 办理区需要可编辑的截止日期，人工调整后要能覆盖自动推算值，
--      且退回重办重新进入节点时以自动值重新起算。
--
-- 处理：deadline_reminder 增加 manual_date，记录人工调整后的日期；
--       为空表示未调整，按「发生日期 + 节点时限（工作日）」自动推算。
-- 注意：MySQL 8.0 不支持 ADD COLUMN IF NOT EXISTS，本脚本只能执行一次；
--       重复执行会报 1060 (Duplicate column name)，属预期。
-- =============================================================

ALTER TABLE deadline_reminder
    ADD COLUMN manual_date DATE NULL COMMENT '人工调整后的截止日期，为空表示按节点时限自动推算' AFTER deadline_date;
